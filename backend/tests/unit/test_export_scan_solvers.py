class Test모든_덱_공통:
    def test_어느_덱에서도_값_줄을_잃지_않는다(self) -> None:
        """**줄이 사라지는 것이 가장 나쁘다.** 잘못 읽은 칸은 화면에 보이지만,
        없어진 줄은 어디에도 안 보인다."""
        decks = {
            "abaqus": (ABAQUS, 5),
            "hm_abaqus": (HM_ABAQUS, 3),
            "nastran": (NASTRAN, 2),
            "lsdyna": (LSDYNA, 1),
            "lsdyna_curve": (LSDYNA_CURVE, 3),
            "ansys": (ANSYS, 3),
            "radioss": (RADIOSS, 1),
        }
        for name, (text, expected) in decks.items():
            found = scan.scan(text)
            covered = sum(max(one.rows, 1) for one in found.lines if one.cells)
            assert covered == expected, f"{name}: {expected}줄이어야 하는데 {covered}줄"


class Test읽고_다시_낸다:
    """**남의 덱을 읽어 정의로 만들고, 그 정의가 같은 모양의 덱을 내는가.**

    이것이 서면 「배포 없이 새 솔버」 가 말뿐이 아니게 된다 — 읽기만 되고 그 모양
    으로 못 내면 초안은 종이일 뿐이다.
    """

    def test_nastran_왕복(self) -> None:
        from matcore import export
        from matcore.export import template

        found = scan.scan(NASTRAN.splitlines()[1] + "\n")
        line = found.lines[0]
        assert (line.width, line.align) == (8, "left")

        fmt = ["fixed_left" if line.align == "left" else "fixed", line.width, 1]
        spec = {
            "lines": [
                {
                    "prefix": line.prefix,
                    "join": "",
                    "fields": [
                        # **값 줄의 상수.** 재료 번호는 카드에서 오지 않는다.
                        {"const": "1       "},
                        {"value": "elastic.youngs_modulus", "format": fmt},
                        {"value": "elastic.poisson_ratio", "format": fmt},
                        {"value": "elastic.density", "format": fmt},
                    ],
                }
            ]
        }
        deck = export.Deck(
            name="STEEL",
            solver_id=1,
            blocks={
                "elastic": {
                    "values": {
                        "youngs_modulus": 210000.0,
                        "poisson_ratio": 0.3,
                        "density": 7.85e-9,
                    }
                }
            },
            provenance=(),
        )
        made = template.render(spec, deck).text

        back = scan.scan(made).lines[0]
        assert back.prefix == "MAT1    "
        assert (back.width, back.align) == (8, "left"), "낸 덱을 다시 8칸으로 못 읽습니다"
        assert len(back.cells) == 4

    def test_왼쪽_맞춤_형식이_있다(self) -> None:
        """**오른쪽 맞춤만 두면 Nastran·OptiStruct 덱을 낼 수 없다.** 폭만 맞고
        값이 반대쪽에 붙으면 이웃 필드와 붙어 솔버가 둘을 한 값으로 읽는다."""
        from matcore.export import template

        assert "fixed_left" in template.FORMATS
        assert template.FORMATS["fixed_left"](210000.0, (8, 1)) == "2.1E+05 "
        assert template.FORMATS["fixed"](210000.0, (8, 1)) == " 2.1E+05"


#: Nastran 자유 필드에서 **비운 칸**. 네 번째가 전단탄성계수 자리인데, 비우면
#: 「기본값을 쓰라」 는 뜻이다.
NASTRAN_EMPTY = "MAT1,1,210000.,,0.3,7.85E-9\n"

#: 연속 카드. 한 논리 줄이 여러 물리 줄로 나뉜다.
NASTRAN_CONT = """TABLES1        2
+       0.0     250.0    0.01     300.0
+      0.05     340.0    0.10     360.0
+      0.15     370.0    0.20     375.0
"""


class Test비운_칸:
    """**빈 칸을 빼고 세면 뒤 값이 한 칸씩 당겨진다.**

    `MAT1,1,210000.,,0.3,7.85E-9` 의 네 번째는 전단탄성계수 자리다. 그것을 빼고
    세면 `0.3`(푸아송비)이 그 자리로 가고 밀도가 푸아송비 자리로 간다 — 해석은
    그대로 돌고, 솔버는 아무 말도 하지 않는다.
    """

    def test_자리를_지킨다(self) -> None:
        cells = _only(NASTRAN_EMPTY).cells
        assert [cell.text for cell in cells] == ["1", "210000.", "", "0.3", "7.85E-9"]
        assert [cell.empty for cell in cells] == [False, False, True, False, False]

    def test_빈_칸에는_이름을_안_붙인다(self) -> None:
        # 0 으로 읽어 「0 인 값」 을 제안하면 비워 둔 자리가 값으로 채워진다.
        #
        # **막는 겹이 둘이다** — `_suggest` 가 0 인 값을 애초에 제안하지 않고,
        # 빈 칸은 그와 별개로 제안을 건너뛴다. 그래서 한쪽만 망가뜨리면 이 시험은
        # 통과한다(2026-08-30 확인). 겹이 둘인 것 자체는 그대로 둔다 — 빈 칸의
        # 값을 0 으로 두는 한 앞 겹이 우연히 지켜 주는 것이고, 그 우연에 기대지
        # 않는 것이 뒤 겹이다.
        found = scan.scan(NASTRAN_EMPTY, {"elastic.zero": 0.0})
        assert all(cell.suggested is None for cell in found.lines[0].cells if cell.empty)

    def test_줄_끝_쉼표는_칸이_아니다(self) -> None:
        # `*DENSITY` 다음 줄이 `7.85E-09,` 다 — 꼬리지 빈 칸이 아니다.
        line = _only("7.85E-09,\n")
        assert len(line.cells) == 1
        assert line.suffix == ","


class Test연속_카드:
    """`+` 로 이어지는 줄. **접두로 잡히므로 표로 묶인다** — 한계라고 적었던 것이
    실은 이미 되고 있었다(2026-08-30 확인)."""

    def test_연속_줄이_표가_된다(self) -> None:
        found = scan.scan(NASTRAN_CONT)
        table = next(one for one in found.lines if one.kind == "rows")
        assert table.rows == 3
        assert table.prefix == "+       "
        assert len(table.cells) == 4

    def test_머리_줄의_폭을_짐작하지_않는다(self) -> None:
        """`TABLES1        2` 를 16칸으로 쟀었다. 실제로는 8칸 둘이고 앞칸이
        키워드다 — **값 하나로는 알 수 없고, 틀린 폭보다 자유 형식이 안전하다.**"""
        head = next(one for one in scan.scan(NASTRAN_CONT).lines if one.cells)
        assert head.width is None
