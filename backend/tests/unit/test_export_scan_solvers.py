"""여러 솔버의 실제 덱을 읽는다 — **이 창구가 열리는 솔버가 몇 개인가.**

`test_export_scan.py` 가 읽는 규칙 하나하나를 보는 곳이라면, 여기는 **덱 한 벌씩**
을 통째로 먹여 「이 솔버는 붙일 만한가」 에 답한다. 붙일 만하다는 것은 초안이
대체로 맞아서 **사람이 값 이름만 채우면 되는** 상태를 뜻한다.

무는 자리는 솔버마다 다르지만 성격은 하나다 — **칸이 하나 늘거나 줄면 그 덱은
모든 값이 밀린 채로 나가고, 솔버는 그것을 오류로 알려 주지 않는다.**

실측(2026-08-30)으로 여기서 다섯을 잡았다:

    Nastran 축약 지수      `7.85-9` 를 `7.85` 와 `-9` 로 읽었다. 값도 칸 수도 틀렸다.
    Nastran 왼쪽 맞춤      `MAT1` 이 첫 칸을 차지해 폭을 못 쟀다.
    ANSYS 세 물성이 한 표    `MP,EX`·`MP,PRXY`·`MP,DENS` 가 숫자 개수만 같아 묶였다 —
                          **두 줄이 사라졌다.**
    접두 글자를 담을 데 없음   `MP,EX,`·`MAT1` 을 못 적으면 그 솔버는 아예 못 붙인다.
    고정폭의 앞 공백        첫 칸의 패딩인데 접두로 잡혀 줄이 두 번 밀렸다.
"""

from __future__ import annotations

from matcore.export import scan

ABAQUS = """*MATERIAL, NAME=STEEL
*ELASTIC
210000., 0.3
*PLASTIC
250., 0.
300., 0.02
340., 0.05
*DENSITY
7.85E-09,
"""

#: HyperMesh 가 낸 Abaqus. 머리에 주석이 붙고 버전 번호가 들어 있다.
HM_ABAQUS = """**HM_ADD_COMMENTS
**  Abaqus Input Deck Generated by HyperMesh Version : 2021
*MATERIAL, NAME=steel
*ELASTIC, TYPE=ISOTROPIC
210000., 0.3, 20.
190000., 0.31, 200.
170000., 0.32, 400.
"""

#: Nastran / OptiStruct 벌크 데이터. **고정 8칸 왼쪽 맞춤**이고 지수의 `E` 가 없다.
NASTRAN = """$ HyperMesh
MAT1    1       210000. .3      7.85-9
MAT1    2       70000.  .33     2.7-9
"""

#: Nastran 자유 필드. 쉼표로 가른다.
NASTRAN_FREE = "MAT1,1,210000.,0.3,7.85E-9\n"

#: LS-DYNA. 열 이름을 `$#` 주석으로 적고 값은 **고정 10칸 오른쪽 맞춤**이다.
LSDYNA = """*MAT_PIECEWISE_LINEAR_PLASTICITY
$#     mid        ro         e        pr      sigy      etan
         1 7.850E-09 2.100E+05     0.300 2.500E+02     0.000
"""

#: LS-DYNA 곡선. **고정 20칸**.
LSDYNA_CURVE = """*DEFINE_CURVE
$#                a1                  o1
           0.0000000         250.0000000
           0.0200000         300.0000000
           0.0500000         340.0000000
"""

#: ANSYS Mechanical APDL. **명령·물성 이름이 값과 같은 줄에** 있다.
ANSYS = """! steel
MP,EX,1,2.1E5
MP,PRXY,1,0.3
MP,DENS,1,7.85E-9
"""

#: OpenRadioss. 키워드가 `/`, 주석이 `#`, 값은 고정 20칸.
RADIOSS = """/MAT/LAW36/1
steel
#                  E                  NU
        2.100000E+05        3.000000E-01
"""


def _values(text: str) -> list[list[str]]:
    """값 줄들의 칸만. 칸 수가 맞는지가 이 시험의 절반이다."""
    return [[cell.text for cell in one.cells] for one in scan.scan(text).lines if one.cells]


def _only(text: str) -> scan.ScannedLine:
    return next(one for one in scan.scan(text).lines if one.cells)


class TestAbaqus:
    def test_키워드와_표가_갈린다(self) -> None:
        found = scan.scan(ABAQUS)
        kinds = [one.kind for one in found.lines]
        assert kinds.count("rows") == 1, kinds
        assert kinds.count("text") == 4

    def test_소수점만_붙은_표기를_읽는다(self) -> None:
        # `210000.` · `0.` — Abaqus 덱에 흔하다. 통째로 한 값이어야 한다.
        assert _values(ABAQUS)[0] == ["210000.", "0.3"]

    def test_밀도_줄의_쉼표를_지킨다(self) -> None:
        density = [one for one in scan.scan(ABAQUS).lines if len(one.cells) == 1]
        assert density and density[0].suffix == ","

    def test_hypermesh_머리를_넘기고_온도표를_읽는다(self) -> None:
        found = scan.scan(HM_ABAQUS)
        # 버전 번호 2021 이 값이 되면 안 된다.
        assert not found.lines[1].cells
        table = [one for one in found.lines if one.kind == "rows"]
        assert len(table) == 1 and table[0].rows == 3
        assert len(table[0].cells) == 3, "온도까지 세 칸이어야 합니다"


class TestNastran:
    def test_생략된_지수를_편다(self) -> None:
        """**`7.85-9` 는 `7.85e-9` 다.** 두 개로 읽으면 칸이 하나 늘고, 그러면
        그 덱은 모든 값이 한 칸씩 밀린다."""
        rows = _values(NASTRAN)
        assert rows[0] == ["1", "210000.", ".3", "7.85-9"]
        cells = _only(NASTRAN).cells
        assert cells[-1].value == 7.85e-9

    def test_왼쪽_맞춤_8칸을_잰다(self) -> None:
        # `MAT1` 이 첫 칸을 차지한다 — 줄 길이를 칸 수로 나누는 방식으로는 못 잰다.
        assert _only(NASTRAN).width == 8

    def test_키워드를_접두로_담는다(self) -> None:
        """**못 담으면 이 솔버는 아예 정의로 못 붙인다.** 공백까지 그대로 둔다 —
        고정폭에서는 그 공백이 칸을 채우는 몫이다."""
        assert _only(NASTRAN).prefix == "MAT1    "

    def test_같은_카드_둘은_표가_아니다(self) -> None:
        # `MAT1 1` 과 `MAT1 2` 는 **다른 재료**다. 둘뿐이라 표로 안 묶인다.
        assert [one.kind for one in scan.scan(NASTRAN).lines if one.cells] == [
            "fields",
            "fields",
        ]

    def test_자유_필드도_읽는다(self) -> None:
        assert _values(NASTRAN_FREE)[0] == ["1", "210000.", "0.3", "7.85E-9"]
        assert _only(NASTRAN_FREE).prefix == "MAT1,"
        # 쉼표로 가르면 고정폭이 아니다.
        assert _only(NASTRAN_FREE).width is None


