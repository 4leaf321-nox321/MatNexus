"""카드 각주 가운데 **확정 전에 사람이 봐야 할 것**을 고른다.

카드의 `source.notes` 에는 두 종류가 섞여 있다 — 값이 어디서 왔는지 적는 말(「푸아송비:
재료에 적힌 값입니다」 · 「시편 3건을 'pooled' 방법으로 묶어 만들었습니다」)과, 값을 그대로
믿으면 안 된다는 말(「밀도가 없습니다」 · 「실측이 아니다」 · 「외삽한 값입니다」).

워크벤치가 둘을 한데 세어 「경고가 붙어 있습니다」 라고 했더니 개발 DB 의 카드 42장이
**전부** 경고 카드로 섰다(2026-10-04 점검). 늘 켜진 경고는 아무도 안 읽는다.

## 문구의 표지로 가른다

각주에 등급이 따로 없다 — 각주를 쓰는 쪽(카드 생성 · 합성 · 적합 · 확장)이 여럿이고 전부
문장 하나를 낸다. 그래서 **문장의 표지**로 가른다. 표지는 그 쪽들의 실제 문장에서 뽑았고,
`tests/unit/test_card_notes.py` 가 그 문장들로 묶어 둔다.

새 경고 문장이 표지를 안 가지면 「출처 설명」 으로 읽힌다. 반대 방향(출처 설명을 경고로
세기)보다 이쪽을 고른 이유: 워크벤치의 판정은 안내지 잠금이 아니고(ADR 0024), 근거 보기
단계는 경고가 없어도 「근거를 보세요」 를 말한다 — 놓친 경고 하나보다 늘 켜진 경고가 더 많이
읽히지 않는다.
"""

from __future__ import annotations

from collections.abc import Iterable

#: 「이 값을 그대로 믿지 말라」 를 뜻하는 표지. 앞의 것이 흔하다.
CAUTION_MARKS = (
    # 밀도 · 푸아송비가 없다 · 시험에서 나온 값이 하나도 없다(재료에 적힌 값으로만)
    "없습니다",
    # 합성 소성 표 — 항복 · UTS · 연신율에서 지은 근사 곡선
    "실측이 아니",
    "합성 주의",
    # 완화시간이 관측 범위 경계에 붙었다
    "외삽",
    # 네킹 뒤까지 섞인 곡선
    "네킹을 안 자른",
    # 시편 하나의 값 — 재료의 대푯값이 아니다
    "대푯값이 아니",
    "평균이 아니",
)


def cautions(notes: Iterable[object] | None) -> list[str]:
    """각주 중 경고인 것. **순서를 지킨다** — 화면이 앞의 것부터 보인다."""
    return [
        text
        for text in (str(one) for one in (notes or []))
        if any(mark in text for mark in CAUTION_MARKS)
    ]
